#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const gluePath = path.join(root, "wasm/audio/dsp_core.js");
const processorPath = path.join(root, "dsp-worklet.js");
const outputPath = path.join(root, "wasm/audio/dsp-worklet.js");
let glue = await readFile(gluePath, "utf8");
glue = glue
  .replace(/^export class DspEngine/m, "class DspEngine")
  .replace(/^export function abi_version/m, "function abi_version")
  .replace(/^export \{ initSync, __wbg_init as default \};\s*$/m, "")
  // TextDecoder is absent in some AudioWorkletGlobalScope implementations. It
  // is only needed to format exceptional Rust panics, never in process().
  .replace(/let cachedTextDecoder =[\s\S]*?function decodeText\(ptr, len\) \{[\s\S]*?\n\}/, `function decodeText(ptr, len) {
    const bytes = getUint8ArrayMemory0().subarray(ptr, ptr + len);
    let text = "";
    for (let index = 0; index < bytes.length; index++) text += String.fromCharCode(bytes[index]);
    return text;
}`);
if (/^export /m.test(glue)) throw new Error("Unhandled wasm-bindgen export while building AudioWorklet");
const processor = await readFile(processorPath, "utf8");
await writeFile(outputPath, `// GENERATED by scripts/build-audio-worklet.mjs; do not edit.\n${glue}\n${processor}`);
console.log(`Built self-contained AudioWorklet: ${outputPath}`);
